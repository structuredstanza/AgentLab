// SetAssetStore wires the asset store and company store onto this ToolSet
// so the insert_assets, add_company_scope, and list_assets tools are active.
func (t *ToolSet) SetAssetStore(as *db.AssetStore, cs *db.CompanyStore) {
	t.as = as
	t.cs = cs
}

// assetInputItem is one element of the insert_assets "assets" array.
type assetInputItem struct {
	Type string `json:"type"` // root_domain|ip|subdomain|app|service|endpoint

	// ---- root_domain / subdomain ----
	Domain      string   `json:"domain"`
	ICP         string   `json:"icp"`
	RecordType  string   `json:"record_type"`
	RecordValue []string `json:"record_value"`

	// ---- ip ----
	IP           string           `json:"ip"`
	BoundDomains []string         `json:"bound_domains"`
	OpenPorts    []db.PortService `json:"open_ports"`

	// ---- app ----
	AppName     string `json:"app_name"`
	BundleID    string `json:"bundle_id"`
	Category    string `json:"category"`
	Description string `json:"description"`
	AppICP      string `json:"app_icp"`
	CompanyID   *int64 `json:"company_id"` // explicit company link (app only; others auto-attribute via scope)

	// ---- service (http) ----
	URL           string           `json:"url"`
	Technologies  []string         `json:"technologies"`
	StatusCode    *int             `json:"status_code"`
	ContentLength *int64           `json:"content_length"`
	PageTitle     string           `json:"page_title"`
	FaviconMMH3   string           `json:"favicon_mmh3"`
	Auth          []map[string]any `json:"auth"`
	ServiceName   string           `json:"service_name"`
	ServiceIP     string           `json:"service_ip"` // optional enrichment IP

	// ---- service (other) ----
	Port  int    `json:"port"`
	Proto string `json:"proto"`

	// ---- endpoint ----
	Method string           `json:"method"`
	Params []map[string]any `json:"params"`
}

// insertAssets is the unified insert_assets agent tool.
func (t *ToolSet) insertAssets() actool.CoreTool {
	return writeTool(
		"insert_assets",
		"Batch-register newly discovered assets; one call may mix several types (see the type enum).\n"+
			"Required fields by type: root_domain->domain; ip->ip (must be an IPv4/IPv6 address, not a hostname); subdomain->domain; app->app_name; service (HTTP)->url; service (non-HTTP)->service_name+port (at least one of ip/domain); endpoint->url+method. See each field's description for the rest.\n"+
			"auth/technologies/params are appended and merged, not overwritten.\n"+
			"Returns: {results:[{index,id,type}], errors:[{index,error}]}",
		obj(map[string]any{
			// task_id is not exposed to the model: which task a worker belongs to is authoritatively assigned by the program via SetTaskID (see handler).
			"assets": map[string]any{
				"type":        "array",
				"description": "Asset array; each element is one asset record",
				"items": obj(map[string]any{
					"type": map[string]any{
						"type":        "string",
						"enum":        []string{"root_domain", "ip", "subdomain", "app", "service", "endpoint"},
						"description": "Asset type",
					},
					// root_domain / subdomain
					"domain":      str("Root domain or subdomain (required for root_domain/subdomain)"),
					"icp":         str("ICP filing number (optional)"),
					"record_type": str("DNS record type: A/AAAA/CNAME/MX etc. (optional for subdomain)"),
					"record_value": map[string]any{
						"type":        "array",
						"items":       map[string]any{"type": "string"},
						"description": "DNS record value list (optional for subdomain, e.g. [\"1.2.3.4\",\"2.3.4.5\"])",
					},
					// ip
					"ip": str("IP address; must be an IPv4/IPv6 address, not a hostname (use the domain field with type=subdomain for hostnames). Required for type ip; optional for service/endpoint to link the IP"),
					"bound_domains": map[string]any{
						"type":        "array",
						"items":       map[string]any{"type": "string"},
						"description": "Domains bound to this IP (optional for type ip)",
					},
					"open_ports": map[string]any{
						"type":        "array",
						"description": "Open port list (optional for type ip)",
						"items": obj(map[string]any{
							"port":    intp("Port number"),
							"service": str("Service name, e.g. http/ssh/mysql (optional)"),
						}, "port"),
					},
					// app
					"app_name":    str("App name (required for type app)"),
					"bundle_id":   str("Bundle ID (optional for type app)"),
					"category":    str("App category (optional)"),
					"description": str("App description (optional)"),
					"app_icp":     str("App ICP filing (optional)"),
					"company_id":  intp("Owning company id (optional for type app; apps cannot be attributed by scope automatically, so it must be given explicitly. Returned by add_company_scope)"),
					// service (http)
					"url":         str("Full URL including protocol and port (required for HTTP services; service_type is set to http automatically)"),
					"status_code": intp("HTTP response status code, e.g. 200/301/403/404 (optional)"),
					"content_length": map[string]any{
						"type":        "integer",
						"description": "HTTP response body size in bytes (optional)",
					},
					"page_title":   str("Page <title> content (optional)"),
					"favicon_mmh3": str("favicon MMH3 hash (optional)"),
					"technologies": map[string]any{
						"type":        "array",
						"items":       map[string]any{"type": "string"},
						"description": "Fingerprint/tech stack list, e.g. [\"Nginx\",\"Vue\",\"Bootstrap\"] (optional)",
					},
					"auth": map[string]any{
						"type":        "array",
						"description": "Discovered credentials; each entry has fields such as type/username/password (optional; appended, not overwritten)",
						"items":       map[string]any{"type": "object"},
					},
					// service (other, not HTTP)
					"service_name": str("Service name, e.g. ssh/mysql/redis (required when service is non-HTTP)"),
					"port":         intp("Port number (required when service is non-HTTP)"),
					// endpoint
					"method": str("HTTP method: GET/POST/PUT/PATCH/DELETE etc. (required for endpoint)"),
					"params": map[string]any{
						"type":        "array",
						"description": "Request parameter list; each entry has location (query/body/header/path), name, value, type (optional; appended, not overwritten)",
						"items":       map[string]any{"type": "object"},
					},
				}, "type"),
			},
		}, "assets"),
		func(_ context.Context, in json.RawMessage) (actool.Result, error) {
			if t.as == nil {
				return actool.Errorf("insert_assets is disabled: AssetStore is not initialized"), nil
			}
			var a struct {
				Assets []assetInputItem `json:"assets"`
			}
			if err := json.Unmarshal(in, &a); err != nil {
				return actool.Errorf("invalid input: " + err.Error()), nil
			}
			// task_id is authoritatively assigned by the program (worker: SetTaskID) and is not accepted from the model, to avoid the model omitting or mis-passing it
			// causing assets to be left unassigned to a task or assigned to the wrong one. For callers without task context (auto/pentest/chat), t.taskID=0.
			taskID := t.taskID

			type result struct {
				Index int    `json:"index"`
				ID    int64  `json:"id"`
				Type  string `json:"type"`
			}
			type errEntry struct {
				Index int    `json:"index"`
				Error string `json:"error"`
			}

			var results []result
			var errs []errEntry

			// Asset gate rules are loaded once. A read failure must fail the
			// call, not skip the judgment: the rules are the operator's
			// authorization boundary, so "could not check" has to mean "did not
			// run" rather than "allowed everything". This is exactly the state
			// a pool-exhaustion error produces, i.e. it would fail open at the
			// worst moment.
			// Intercept rules = global ∪ task-level block; allow rules = task-level allow.
			blockRules, err := t.as.ListAssetInterceptRules()
			if err != nil {
				return actool.Errorf("asset gate rules unavailable, refusing to insert without them: " + err.Error()), nil
			}
			var allowRules []db.AssetInterceptRule
			if t.taskID > 0 {
				tb, ta, err := t.as.TaskInterceptRulesSplit(t.taskID)
				if err != nil {
					return actool.Errorf("task asset gate rules unavailable, refusing to insert without them: " + err.Error()), nil
				}
				blockRules = append(blockRules, tb...)
				allowRules = ta
			}

			for i, item := range a.Assets {
				// Asset gate: check block first, then allow. Rejected assets are forbidden from being inserted (skip Upsert and all subsequent side effects).
				domains, ips, urls := assetInterceptCandidates(item)
				if d := db.EvaluateAssetGate(blockRules, allowRules, domains, ips, urls); !d.Allowed {
					errs = append(errs, errEntry{
						Index: i,
						Error: fmt.Sprintf("asset %s %s; insertion is forbidden", assetInputLabel(item), d.Reason),
					})
					continue
				}

				typ := strings.TrimSpace(item.Type)
				var id int64
				var err error

				switch typ {
				case "root_domain":
					id, err = t.as.UpsertRootDomain(db.UpsertRootDomainReq{
						Domain: item.Domain,
						ICP:    item.ICP,
						TaskID: taskID,
					})

				case "ip":
					id, err = t.as.UpsertIP(db.UpsertIPReq{
						IP:           item.IP,
						BoundDomains: item.BoundDomains,
						OpenPorts:    item.OpenPorts,
						TaskID:       taskID,
					})

				case "subdomain":
					id, err = t.as.UpsertSubdomain(db.UpsertSubdomainReq{
						Domain:      item.Domain,
						RecordType:  item.RecordType,
						RecordValue: item.RecordValue,
						ICP:         item.ICP,
						TaskID:      taskID,
					})

				case "app":
					id, err = t.as.UpsertApp(db.UpsertAppReq{
						Name:        item.AppName,
						BundleID:    item.BundleID,
						Category:    item.Category,
						Description: item.Description,
						ICP:         item.AppICP,
						CompanyID:   item.CompanyID,
						TaskID:      taskID,
					})

				case "service":
					// distinguish HTTP vs other by presence of url
					if item.URL != "" {
						// agent may send "ip" or "service_ip" for the enrichment IP; accept both
						svcIP := item.ServiceIP
						if svcIP == "" {
							svcIP = item.IP
						}
						id, err = t.as.UpsertHTTPService(db.UpsertHTTPServiceReq{
							URL:           item.URL,
							Technologies:  item.Technologies,
							StatusCode:    item.StatusCode,
							ContentLength: item.ContentLength,
							PageTitle:     item.PageTitle,
							FaviconMMH3:   item.FaviconMMH3,
							Auth:          item.Auth,
							IP:            svcIP,
							TaskID:        taskID,
						})
					} else {
						id, err = t.as.UpsertOtherService(db.UpsertOtherServiceReq{
							Domain:      item.Domain,
							IP:          item.IP,
							Port:        item.Port,
							ServiceName: item.ServiceName,
							Auth:        item.Auth,
							TaskID:      taskID,
						})
					}

				case "endpoint":
					id, err = t.as.UpsertEndpoint(db.UpsertEndpointReq{
						URL:    item.URL,
						Method: item.Method,
						Params: item.Params,
						IP:     item.ServiceIP,
						TaskID: taskID,
					})

				default:
					errs = append(errs, errEntry{Index: i, Error: "unknown type: " + typ})
					continue
				}

				if err != nil {
					errs = append(errs, errEntry{Index: i, Error: err.Error()})
					continue
				}
				results = append(results, result{Index: i, ID: id, Type: typ})
				t.writes.Assets++
				t.anchorOwner(id)
				if taskID > 0 {
					var sourceNodeID *int64
					if t.ownerNode > 0 {
						nodeID := t.ownerNode
						sourceNodeID = &nodeID
					}
					summary := "Agent registered via insert_assets"
					if t.ownerNode > 0 {
						summary = fmt.Sprintf("Worker intent #%d registered via insert_assets", t.ownerNode)
					}
					_ = t.as.SetTaskAssetSource(taskID, id, "agent", summary, sourceNodeID)
				}
				// Auto-add to test scope (source='auto'): applies only to the single item explicitly inserted at the top level of the worker, based on its
				// Type plus a conservative scope; assets derived from side-effect are not handled here, so the scope is not blindly expanded. No-op when taskID=0.
				// Independent of the coverage toggle: task_scope is the task's scope boundary (the filter baseline for list/query operations),
				// the coverage toggle only decides whether to use it as the denominator when computing metrics, not whether to accumulate the scope itself.
				{
					svcIP := item.ServiceIP
					if svcIP == "" {
						svcIP = item.IP
					}
					_ = t.as.AddAutoScope(taskID, typ, item.Domain, item.URL, svcIP)
				}
				// Async engine-side auto-completion for what was just persisted: DNS
				// for a domain, an HTTP probe for a web service. The engine re-checks
				// the destination against this task's boundary at dispatch (and again
				// for every redirect), so this call only chooses the work kind. A
				// task-less caller (auto/chat) has no boundary to check and the engine
				// drops it there rather than enriching on nobody's authority.
				t.enrichAsset(taskID, typ, id, item)
			}

			return jsonResult(map[string]any{
				"results": results,
				"errors":  errs,
			})
		},
	)
}

// enrichAsset schedules engine-side auto-completion for one asset that was just
// persisted: DNS resolution for a domain asset, an HTTP probe for a web service.
// Nothing is scheduled for an IP, app, non-HTTP service or endpoint — there is no
// new host to reach for those, and probing an endpoint URL would be contact the
// insert itself did not authorize.
//
// The destination is NOT checked here: the engine is shared by every task, so it
// re-checks the target (and every redirect) against the owning task's boundary at
// dispatch, where the task identity is still attached. No engine, no task, or an
// asset that failed to persist → nothing is scheduled.
func (t *ToolSet) enrichAsset(taskID int64, typ string, id int64, item assetInputItem) {
	if t.enrich == nil || taskID <= 0 || id <= 0 {
		return
	}
	switch typ {
	case "root_domain", "subdomain":
		if host := strings.TrimSpace(item.Domain); host != "" {
			t.enrich.ResolveDomain(taskID, id, host)
		}
	case "service":
		if rawURL := strings.TrimSpace(item.URL); rawURL != "" {
			t.enrich.ProbeSite(taskID, id, rawURL)
		}
	}
}

// addCompanyScope writes to company_scope table and triggers asset attribution.
func (t *ToolSet) addCompanyScope() actool.CoreTool {
	return writeTool(
		"add_company_scope",
		"Add domains/IPs/CIDRs/ICP filings/company keywords to a company's [asset scope]. Domains, networks and ICP filings automatically claim matching assets; keywords are only given to the Agent as scope hints.\n"+
			"Company names are unique: if the company does not exist it is created; if it exists it is reused (scope is merged in).\n"+
			"One scope entry per line; the system auto-detects: root domain / URL / single IP / CIDR block / ICP filing / company keyword.\n"+
			"Always provide reason with the ownership basis (whois/certificate/ASN etc.).\n"+
			"Guardrails: bare TLDs and overly broad ranges are rejected (IPv4 prefix must be /16-/32, IPv6 prefix must be /32-/128); invalid lines are skipped and returned in errors.",
		obj(map[string]any{
			"company": str("Company name (created if it does not exist, reused if it does; names are unique)"),
			"scope":   str("Asset scope, one entry per line: domain / URL / IP / CIDR / ICP filing / company keyword"),
			"reason":  str("Basis of ownership (evidence/source); always provide"),
			"logo":    str("Company logo URL (optional; applies only when the company is created)"),
		}, "company", "scope"),
		func(_ context.Context, in json.RawMessage) (actool.Result, error) {
			if t.cs == nil {
				return actool.Errorf("add_company_scope is disabled: CompanyStore is not initialized"), nil
			}
			var a struct {
				Company string `json:"company"`
				Scope   string `json:"scope"`
				Reason  string `json:"reason"`
				Logo    string `json:"logo"`
			}
			if err := json.Unmarshal(in, &a); err != nil {
				return actool.Errorf(err.Error()), nil
			}
			if strings.TrimSpace(a.Company) == "" {
				return actool.Errorf("company must not be empty"), nil
			}
			companyID, _, err := t.cs.UpsertCompany(a.Company, a.Logo)
			if err != nil {
				return actool.Errorf("failed to create/get company: " + err.Error()), nil
			}
			lines := splitLines(a.Scope)
			added, skipped, invalid, errMsgs := t.cs.AddScope(companyID, lines, a.Reason)
			out := map[string]any{
				"company_id": companyID,
				"added":      added,
				"skipped":    skipped,
				"invalid":    invalid,
			}
			if len(errMsgs) > 0 {
				out["errors"] = errMsgs
			}
			return jsonResult(out)
		},
	)
}

// addTaskScope lets the plan agent add test scope to THE CURRENT TASK — the coverage
// denominator and the task's authorization edge. Worker discoveries are auto-scoped
// (precise host) by insertAssets; this tool is for DELIBERATELY WIDENING: pull a whole
// root domain or whole company into scope, or add a specific subdomain / ip.
func (t *ToolSet) addTaskScope() actool.CoreTool {
	return writeTool(
		"add_task_scope",
		"Add test scope to [this task]: this is the task's authorization boundary and the denominator for asset test coverage.\n"+
			"kind supports: company (all assets under a company) / root_domain (a whole root domain, including all subdomains) / subdomain (a single exact subdomain) / ip / cidr / icp / keyword.\n"+
			"Note: hosts the worker encounters are added to scope automatically by the system (exact subdomains); this tool is for actively expanding scope: adding a whole root domain or company, or adding a specific subdomain or IP.\n"+
			"value: for company, pass the company name or id (the company must already exist); for root_domain/subdomain pass the domain; for ip/cidr pass an IP or range; for icp/keyword pass the filing number or company keyword.\n"+
			"Always provide reason with the basis (auditable). Use the entries array for multiple items.",
		obj(map[string]any{
			"entries": map[string]any{"type": "array", "description": "Batch: [{kind, value, effect}]. kind is one of company/root_domain/subdomain/ip/cidr/icp/keyword; effect is include (default) or exclude.", "items": map[string]any{"type": "object"}},
			"kind":    str("[Single] company / root_domain / subdomain / ip / cidr / icp / keyword"),
			"value":   str("[Single] company name or id / domain / IP / CIDR / ICP filing / keyword"),
			"effect":  str("[Single] include (default) or exclude. exclude means the operator forbids this host: the tool guard refuses any call naming it, and it always wins over an include. Only root_domain / subdomain / ip / cidr can be excluded; company / icp / keyword are matched against asset attributes and are refused as exclusions."),
			"reason":  str("Reason for adding (for audit); always provide"),
		}),
		func(_ context.Context, in json.RawMessage) (actool.Result, error) {
			if t.as == nil {
				return actool.Errorf("add_task_scope is disabled: AssetStore is not initialized"), nil
			}
			if t.taskID <= 0 {
				return actool.Errorf("add_task_scope requires a task context (no current task)"), nil
			}
			type scopeEntry struct {
				Kind   string `json:"kind"`
				Value  string `json:"value"`
				Effect string `json:"effect"`
			}
			var a struct {
				Entries    []scopeEntry `json:"entries"`
				scopeEntry              // Single-item mode
				Reason     string       `json:"reason"`
			}
			_ = json.Unmarshal(in, &a)
			items := a.Entries
			if len(items) == 0 {
				items = []scopeEntry{a.scopeEntry}
			}
			var added []map[string]any
			errs := map[string]string{}
			for i, e := range items {
				ts, err := t.as.AddAgentScope(t.taskID, strings.TrimSpace(e.Kind), e.Value, a.Reason, "agent", e.Effect)
				if err != nil {
					errs[strconv.Itoa(i)] = err.Error()
					continue
				}
				added = append(added, map[string]any{"kind": ts.Kind, "domain": ts.Domain, "net": ts.Net, "value": ts.Value, "company_id": ts.CompanyID, "effect": ts.Effect})
			}
			out := map[string]any{"added": added}
			if len(errs) > 0 {
				out["errors"] = errs
			}
			return jsonResult(out)
		},
	)
}

// listUntestedAssets lets the plan agent pull the current + directly inherited
// scope's not-yet-tested assets on demand (filter by type, paginated).
func (t *ToolSet) listUntestedAssets() actool.CoreTool {
	return readTool(
		"list_untested_assets",
		"Query assets within the scope of [this task and directly linked tasks] that are not yet covered by fact anchors (linked scope is read-only; this is for you to decide whether to test them, it does not decide for you).\n"+
			"Optional filter by asset type: root_domain/subdomain/service/app/endpoint/ip.\n"+
			"Pagination: page starts at 1, page_size defaults to 10. Returns {assets:[{id,type,label}], total, page, page_size}. Only available with a task context.",
		obj(map[string]any{
			"type":      str("Asset type filter (optional): root_domain/subdomain/service/app/endpoint/ip"),
			"page":      intp("Page number, starting at 1 (default 1)"),
			"page_size": intp("Items per page (default 10)"),
		}),
		func(_ context.Context, in json.RawMessage) (actool.Result, error) {
			if t.as == nil {
				return actool.Errorf("list_untested_assets is disabled: AssetStore is not initialized"), nil
			}
			if t.taskID <= 0 || t.ts == nil {
				return actool.Errorf("list_untested_assets requires a task context"), nil
			}
			var a struct {
				Type     string `json:"type"`
				Page     int    `json:"page"`
				PageSize int    `json:"page_size"`
			}
			_ = json.Unmarshal(in, &a)
			if a.Page <= 0 {
				a.Page = 1
			}
			if a.PageSize <= 0 {
				a.PageSize = 10
			}
			offset := (a.Page - 1) * a.PageSize
			assets, total, err := t.as.ListUntestedAssetsWithSources(t.taskID, strings.TrimSpace(a.Type), a.PageSize, offset)
			if err != nil {
				return actool.Errorf(err.Error()), nil
			}
			return jsonResult(map[string]any{
				"assets": assets, "total": total, "page": a.Page, "page_size": a.PageSize,
			})
		},
	)
}

// listAssets lets an agent query the asset table.
func (t *ToolSet) listAssets() actool.CoreTool {
	return readTool(
		"list_assets",
		"Query the asset library: DSL expression search, or fetch directly by id/ids; supports pagination. Returns only assets within the test scope of [this task and directly linked tasks].\n"+
			"DSL: field=value fuzzy (ILIKE) | field==value exact | field!=value exclude | numeric fields support > >= < <= | bare word = full-text fuzzy; combine with AND/OR (AND binds tighter), parentheses allowed for grouping. Asset type uses the separate type parameter, not the DSL.\n"+
			"If id/ids is not given, dsl must be non-empty (unconditional full queries are not allowed).\n"+
			"Available fields: domain (root/subdomain/service domain), root_domain, ip, url, page_title, icp, service_name, app_name, method (e.g. GET/POST), service_type (http|other), record_type (e.g. A/CNAME), technology (array; = fuzzy, == exact), port/status_code/company_id (integers).\n"+
			"Examples: status_code>=400 AND technology=shiro ; (port==80 OR port==443) AND technology=nginx",
		obj(map[string]any{
			"dsl":    str(`DSL query expression (syntax and fields in the tool description). Must be non-empty when id/ids is not given.`),
			"type":   str("Asset type filter: root_domain|ip|subdomain|app|service|endpoint (separate field; can be combined with dsl; type alone is not enough to query, dsl is still required)"),
			"id":     intp("Fetch directly by a single asset id (optional; mutually exclusive with dsl/type)"),
			"ids":    map[string]any{"type": "array", "items": map[string]any{"type": "integer"}, "description": "Fetch directly by multiple asset ids (optional; mutually exclusive with dsl/type)"},
			"limit":  intp("Maximum results, default 10 (optional)"),
			"offset": intp("Pagination offset, default 0 (optional)"),
		}),
		func(_ context.Context, in json.RawMessage) (actool.Result, error) {
			if t.as == nil {
				return actool.Errorf("list_assets is disabled: AssetStore is not initialized"), nil
			}
			var a struct {
				DSL    string  `json:"dsl"`
				Type   string  `json:"type"`
				ID     int64   `json:"id"`
				IDs    []int64 `json:"ids"`
				Limit  int     `json:"limit"`
				Offset int     `json:"offset"`
			}
			_ = json.Unmarshal(in, &a)
			if a.Limit <= 0 {
				a.Limit = 10
			}

			var assets []*db.Asset
			var err error
			switch {
			case a.ID > 0:
				assets, err = t.as.GetByIDsInScope(t.taskID, []int64{a.ID})
			case len(a.IDs) > 0:
				assets, err = t.as.GetByIDsInScope(t.taskID, a.IDs)
			case a.DSL != "":
				assets, err = t.as.QueryDSLInScope(a.DSL, a.Type, t.taskID, a.Limit, a.Offset)
			default:
				return actool.Errorf("dsl must not be empty when id/ids is not given: unconditional queries of all assets are not allowed; provide query conditions"), nil
			}
			if err != nil {
				return actool.Errorf("DSL error: " + err.Error()), nil
			}
			return jsonResult(map[string]any{
				"count":  len(assets),
				"assets": assets,
			})
		},
	)
}

// listCompanies lets an agent enumerate companies (enterprises) with their scope + asset count.
func (t *ToolSet) listCompanies() actool.CoreTool {
	return readTool(
		"list_companies",
		"List companies in the asset library with their scope and attributed asset count, to see which companies exist "+
			"and get company_id (used when insert_assets links an app and when list_assets filters by company_id). "+
			"Optional search does a fuzzy company-name filter (case-insensitive); leave empty to return all.",
		obj(map[string]any{
			"search": str("Fuzzy filter by company name (optional, case-insensitive); leave empty to return all"),
		}),
		func(_ context.Context, in json.RawMessage) (actool.Result, error) {
			if t.cs == nil {
				return actool.Errorf("list_companies is disabled: CompanyStore is not initialized"), nil
			}
			var a struct {
				Search string `json:"search"`
			}
			_ = json.Unmarshal(in, &a)
			cos, err := t.cs.ListCompanies()
			if err != nil {
				return actool.Errorf("failed to query companies: " + err.Error()), nil
			}
			q := strings.ToLower(strings.TrimSpace(a.Search))
			type companyOut struct {
				ID         int64    `json:"id"`
				Name       string   `json:"name"`
				AssetCount int      `json:"asset_count"`
				Scope      []string `json:"scope"`
			}
			out := make([]companyOut, 0, len(cos))
			for _, c := range cos {
				if q != "" && !strings.Contains(strings.ToLower(c.Name), q) {
					continue
				}
				scope := make([]string, 0, len(c.Scope))
				for _, r := range c.Scope {
					scope = append(scope, r.Raw)
				}
				out = append(out, companyOut{ID: c.ID, Name: c.Name, AssetCount: c.AssetCount, Scope: scope})
			}
			return jsonResult(map[string]any{"count": len(out), "companies": out})
		},
	)
}

// splitLines splits a multi-line string into non-empty trimmed lines.
func splitLines(s string) []string {
	var out []string
	for _, line := range strings.Split(s, "\n") {
		line = strings.TrimSpace(line)
		if line != "" {
			out = append(out, line)
		}
	}
	return out
}

// WorkerTools returns the tool set for a work agent.
func (t *ToolSet) WorkerTools() []actool.CoreTool {
	return []actool.CoreTool{
		// list_findings is kept: before reporting a vulnerability, check the vulnerabilities already confirmed in this task to avoid reporting the same one twice.
		t.listFindings(),
		t.addFinding(), t.recordFact(),
		// asset management (handlers guard nil store internally).
		// add_company_scope is not given to workers: defining the enterprise asset scope is the responsibility of planning/orchestration/Auto, while workers only perform exploration.
		t.insertAssets(), t.listAssets(),
		t.saveTaskCredential(), t.listTaskCredentials(),
		// Look back across work: a worker can also reuse observations from other work, to avoid duplicated effort.
		// search_all_worker_traces: no need to know the intent_id in advance; search globally by keyword for matching steps;
		// get_worker_trace: after locking onto a given work, list its steps, search within it in place, or fetch full content.
		t.searchAllWorkerTraces(), t.getWorkerTrace(),
		// node_detail: Once the worker has the intent_id / node id, it can look up the full details of that node (used together with the lookback above).
		t.nodeDetail(),
		// recall / knowledge_add / reflect: the task's operational memory. They stay
		// in the list with a nil store so the DB tool catalog seeds them (handlers
		// refuse clearly without one).
		t.recallTool(), t.knowledgeAddTool(), t.reflectTool(),
		// The following tools are still NOT given to the worker; they are reserved for the planner/main (reading context and reviewing across work items is planning responsibility,
		// worker only executes a single intent and writes back the result: list_facts / list_companies / list_worker_traces.
	}
}

// MainAgentTools returns the human-interface tool set.
func (t *ToolSet) MainAgentTools() []actool.CoreTool {
	return []actool.CoreTool{
		t.graphOverview(), t.listFindings(), t.listFacts(), t.nodeDetail(),
		t.expandDigest(), // cold-digest §6.1
		t.getWorkerOutput(), t.getWorkerTrace(), t.searchAllWorkerTraces(), t.addHint(), t.addIntent(),
		// steer_work: a human can inject a corrective instruction into a running intent (work) in real time, without interrupting it or losing its progress.
		t.steerWorkTool(),
		// set_goals: a human can add a new final goal to the current task at runtime; the planner uses it to re-judge whether the task is complete.
		t.setGoals(),
		// set_constraints: the human can add to or modify operation constraints (allow/deny) for this task at runtime, bounding the planner/worker exploration scope.
		t.setConstraints(),
		// asset management (handlers guard nil store internally)
		t.insertAssets(), t.addCompanyScope(), t.listAssets(),
		t.addFinding(), t.recordFact(),
		t.addTaskScope(),
		// list_untested_assets: On demand, list untested assets within this task's scope (by type, with pagination), and decide on supplementary testing yourself.
		t.listUntestedAssets(),
		// recall / knowledge_add: the operator interface reads and records reusable
		// knowledge (reflect is worker/planner only — an intent's own lesson).
		t.recallTool(), t.knowledgeAddTool(),
	}
}

// AllDomainTools returns the union of all domain tools across all agent types,
// deduped by name (mainagent order wins). Used by the server to build a registry
// for injecting domain tools into agents (Auto, custom) that don't own a per-task
// ToolSet. The caller provides real stores; tools are callable at taskID=0 scope.
func (t *ToolSet) AllDomainTools() []actool.CoreTool {
	seen := map[string]bool{}
	var out []actool.CoreTool
	all := append(append(t.MainAgentTools(), t.PlannerTools()...), t.WorkerTools()...)
	for _, tool := range all {
		if !seen[tool.Name()] {
			seen[tool.Name()] = true
			out = append(out, tool)
		}
	}
	return out
}
