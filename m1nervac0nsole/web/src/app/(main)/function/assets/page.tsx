// The HTTP method keeps its real meaning: safe reads, creation, mutation,
// deletion. Nothing here is decoration, so the tone set stays semantic.
const METHOD_COLOR: Record<string, string> = {
  GET: "border-success/40 text-success",
  POST: "border-info/40 text-info",
  PUT: "border-warning/40 text-warning",
  PATCH: "border-warning/60 text-warning",
  DELETE: "border-destructive/40 text-destructive",
  HEAD: "border-border text-muted-foreground",
  OPTIONS: "border-border text-muted-foreground",
};

function MethodBadge({ method }: { method: string }) {
  const m = method.toUpperCase();
  return (
    <span
      className={cn(
        "inline-block border px-1.5 py-0.5 font-mono font-semibold text-[10px] leading-none",
        METHOD_COLOR[m] ?? "border-border text-muted-foreground",
      )}
    >
      {m || "—"}
    </span>
  );
}

function statusTone(code: number) {
  if (code >= 500) return "text-destructive";
  if (code >= 400) return "text-warning";
  if (code >= 300) return "text-info";
  if (code >= 200) return "text-success";
  return "text-muted-foreground";
}

