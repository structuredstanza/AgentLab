// Package report renders a deliverable Markdown report from the exploration
// graph: confirmed findings (with severity/evidence) (docs §15 P5).
package report

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"
	"time"

	"github.com/structuredstanza/AgentLab/m1nervac0nsole/db"
)

// Input bundles what the report needs.
type Input struct {
	Title       string
	Goal        string
	GeneratedAt time.Time
	AssetCounts map[string]int
	Findings    []*db.Node
	// Uncovered lists in-scope assets with no recorded exploration activity.
	// A report that only enumerates findings silently implies the rest of the
	// scope was clean; naming the untouched assets makes the gap visible.
	// nil means coverage could not be determined (the graph build failed or no
	// asset store was available); a non-nil empty slice means every in-scope
	// asset was touched. Rendering both as "covered" would turn a failed
	// computation into a clean result.
	Uncovered []UncoveredAsset
}

// UncoveredAsset is one in-scope asset nothing on the exploration graph touched.
type UncoveredAsset struct {
	Kind  string
	Label string
}

type findingView struct {
	VulnClass string
	Name      string
	Severity  string
	Summary   string
	PoC       string
}

func parseFinding(n *db.Node) findingView {
	var p struct {
		VulnClass string `json:"vulnclass"`
		Name      string `json:"name"`
		Severity  string `json:"severity"`
		Summary   string `json:"summary"`
		Evidence  struct {
			PoC string `json:"poc"`
		} `json:"evidence"`
	}
	_ = json.Unmarshal(n.Payload, &p)
	return findingView{p.VulnClass, p.Name, p.Severity, p.Summary, p.Evidence.PoC}
}

var sevRank = map[string]int{"critical": 0, "high": 1, "medium": 2, "low": 3, "": 4}

// brandFooter identifies the console in every exported document.
const brandFooter = "\n_Generated by m1nervac0nsole (AGPL-3.0)._\n"

// Markdown renders the report.
func Markdown(in Input) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Penetration Test Report: %s\n\n", nz(in.Title, "Unnamed task"))
	fmt.Fprintf(&b, "- **Task goal**: %s\n", nz(in.Goal, "(not specified)"))
	fmt.Fprintf(&b, "- **Generated at**: %s\n\n", in.GeneratedAt.Format("2006-01-02 15:04:05"))

	// summary
	fmt.Fprintf(&b, "## Summary\n\n")
	fmt.Fprintf(&b, "- Confirmed vulnerabilities: **%d**\n", len(in.Findings))
	fmt.Fprintf(&b, "- Assets: ")
	var types []string
	for t := range in.AssetCounts {
		types = append(types, t)
	}
	sort.Strings(types)
	for i, t := range types {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%s %d", t, in.AssetCounts[t])
	}
	b.WriteString("\n\n")

	// coverage: an untouched in-scope asset is a gap in the engagement, not a
	// clean result, so it is stated even when every finding is documented.
	fmt.Fprintf(&b, "## Coverage\n\n")
	switch {
	case in.Uncovered == nil:
		// A failed computation must not read as a clean scope.
		b.WriteString("_Coverage could not be determined: the in-scope asset graph could not be built, so this report makes no claim that the scope was covered._\n\n")
	case len(in.Uncovered) == 0:
		b.WriteString("_Every in-scope asset had recorded exploration activity._\n\n")
	default:
		fmt.Fprintf(&b, "**%d in-scope asset(s) had no recorded exploration activity.** No finding is claimed for them; treat them as untested, not as clean.\n\n", len(in.Uncovered))
		for _, a := range in.Uncovered {
			fmt.Fprintf(&b, "- `%s` %s\n", nz(a.Kind, "asset"), a.Label)
		}
		b.WriteString("\n")
	}

	// findings
	fmt.Fprintf(&b, "## Vulnerabilities\n\n")
	if len(in.Findings) == 0 {
		b.WriteString("_No vulnerabilities were confirmed this time._\n\n")
	} else {
		fs := make([]findingView, 0, len(in.Findings))
		for _, n := range in.Findings {
			fs = append(fs, parseFinding(n))
		}
		sort.SliceStable(fs, func(i, j int) bool { return sevRankOf(fs[i].Severity) < sevRankOf(fs[j].Severity) })
		for i, f := range fs {
			fmt.Fprintf(&b, "### %d. [%s] %s\n\n", i+1, strings.ToUpper(nz(f.Severity, "info")), nz(f.Name, nz(f.VulnClass, "Unclassified")))
			fmt.Fprintf(&b, "%s\n\n", nz(f.Summary, ""))
			if f.PoC != "" {
				fmt.Fprintf(&b, "**PoC / Evidence:**\n\n```\n%s\n```\n\n", f.PoC)
			}
		}
	}

	b.WriteString("---\n")
	b.WriteString(brandFooter)
	return b.String()
}

func nz(s, d string) string {
	if strings.TrimSpace(s) == "" {
		return d
	}
	return s
}
